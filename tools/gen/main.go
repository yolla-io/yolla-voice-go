// Command gen writes the generated API models (types.gen.go) and the contract
// snapshot as JSON (testdata/contract.json) from openapi/partner-api.yaml.
//
// The snapshot is OpenAPI 3.1 while oapi-codegen reads OpenAPI 3.0, so gen
// feeds the generator a 3.0 copy built from the snapshot (see downconvert).
//
// Usage: gen <repository root> <output directory>. Outputs are written under
// the output directory at the same paths as in the repository.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"runtime/debug"
	"slices"
	"strings"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/util"
	"gopkg.in/yaml.v3"
)

const (
	contractPath = "openapi/partner-api.yaml"
	configPath   = "openapi/oapi-codegen.yaml"
	contractJSON = "testdata/contract.json"
)

// config is the oapi-codegen configuration file, as read by its CLI.
type config struct {
	codegen.Configuration `yaml:",inline"`
	Output                string `yaml:"output"`
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen <repository root> <output directory>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(root, outDir string) error {
	files, err := generate(root)
	if err != nil {
		return err
	}
	for _, name := range slices.Sorted(maps.Keys(files)) {
		path := filepath.Join(outDir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, files[name], 0o644); err != nil {
			return err
		}
	}
	return nil
}

// generate returns the generated files keyed by their path in the repository.
func generate(root string) (map[string][]byte, error) {
	src, err := os.ReadFile(filepath.Join(root, contractPath))
	if err != nil {
		return nil, err
	}
	var doc map[string]any
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", contractPath, err)
	}
	snapshot, err := marshalJSON(doc)
	if err != nil {
		return nil, err
	}

	doc30, err := downconvert(doc)
	if err != nil {
		return nil, err
	}
	spec30, err := marshalJSON(doc30)
	if err != nil {
		return nil, err
	}

	cfgData, err := os.ReadFile(filepath.Join(root, configPath))
	if err != nil {
		return nil, err
	}
	var cfg config
	if err := yaml.Unmarshal(cfgData, &cfg); err != nil {
		return nil, fmt.Errorf("%s: %w", configPath, err)
	}
	if cfg.Output == "" {
		return nil, fmt.Errorf("%s: output is not set", configPath)
	}
	opts := cfg.UpdateDefaults()
	if err := opts.Validate(); err != nil {
		return nil, fmt.Errorf("%s: %w", configPath, err)
	}

	// The loader applies the configured overlay and reads the document from a
	// file, so the 3.0 copy goes through a temporary file.
	tmp, err := os.MkdirTemp("", "yollavoice-gen-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	specFile := filepath.Join(tmp, "partner-api-3.0.json")
	if err := os.WriteFile(specFile, spec30, 0o644); err != nil {
		return nil, err
	}
	overlay := opts.OutputOptions.Overlay
	if overlay.Path != "" {
		overlay.Path = filepath.Join(root, overlay.Path)
	}
	spec, err := util.LoadSwaggerWithOverlay(specFile, util.LoadSwaggerWithOverlayOpts{
		Path:   overlay.Path,
		Strict: overlay.Strict == nil || *overlay.Strict,
	})
	if err != nil {
		return nil, err
	}
	code, err := codegen.Generate(spec, opts)
	if err != nil {
		return nil, err
	}
	if code, err = rewriteHeader(code, generatorVersion()); err != nil {
		return nil, err
	}
	return map[string][]byte{
		filepath.ToSlash(cfg.Output): []byte(code),
		contractJSON:                 snapshot,
	}, nil
}

const generatorModule = "github.com/oapi-codegen/oapi-codegen/v2"

// generatorVersion is the oapi-codegen version pinned in tools/go.mod.
func generatorVersion() string {
	if info, ok := debug.ReadBuildInfo(); ok {
		for _, dep := range info.Deps {
			if dep.Path == generatorModule {
				return dep.Version
			}
		}
	}
	return "unknown"
}

// rewriteHeader replaces the generator's preamble, which is a package doc
// comment naming the tools module, with a plain generated-code notice that
// does not become part of the package documentation.
func rewriteHeader(code, version string) (string, error) {
	i := strings.Index(code, "\npackage ")
	if i < 0 {
		return "", fmt.Errorf("generated code has no package clause")
	}
	header := "// Code generated by oapi-codegen " + version + " from " + contractPath +
		" with make gen. DO NOT EDIT.\n\n"
	return header + code[i+1:], nil
}

// marshalJSON renders v as indented JSON with a trailing newline. Map keys
// are sorted, so the output is deterministic.
func marshalJSON(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// nameMaps are keys whose map value is keyed by names (field names, schema
// names, paths, media types), not by OpenAPI keywords. Their keys are never
// rewritten as keywords.
var nameMaps = map[string]bool{
	"properties": true, "patternProperties": true, "schemas": true, "paths": true,
	"pathItems": true, "parameters": true, "responses": true, "requestBodies": true,
	"securitySchemes": true, "headers": true, "content": true, "encoding": true,
	"links": true, "callbacks": true, "examples": true, "mapping": true,
	"variables": true, "$defs": true,
}

// downconvert returns an OpenAPI 3.0 copy of an OpenAPI 3.1 document. The
// input is not modified. Rewrites:
//   - `type: [X, "null"]` becomes `type: X` with `nullable: true`;
//   - `oneOf`/`anyOf` with a `{type: "null"}` member loses that member and
//     gains `nullable: true`; a single remaining member becomes `allOf: [it]`;
//   - `const: x` becomes `enum: [x]`;
//   - `openapi: 3.1.x` becomes `3.0.3`, and the 3.1-only `webhooks` section
//     is dropped (the components it uses stay).
//
// Everything else is copied unchanged.
func downconvert(doc map[string]any) (map[string]any, error) {
	out, err := convert(doc, false, "")
	if err != nil {
		return nil, err
	}
	m := out.(map[string]any)
	m["openapi"] = "3.0.3"
	delete(m, "webhooks")
	return m, nil
}

// convert deep-copies node. When names is true, node's keys are names and
// node itself is not rewritten; its values still are.
func convert(node any, names bool, path string) (any, error) {
	switch n := node.(type) {
	case map[string]any:
		out := make(map[string]any, len(n))
		for k, v := range n {
			c, err := convert(v, !names && nameMaps[k], path+"/"+k)
			if err != nil {
				return nil, err
			}
			out[k] = c
		}
		if names {
			return out, nil
		}
		return rewriteSchema(out, path)
	case []any:
		out := make([]any, len(n))
		for i, v := range n {
			c, err := convert(v, false, fmt.Sprintf("%s/%d", path, i))
			if err != nil {
				return nil, err
			}
			out[i] = c
		}
		return out, nil
	default:
		return node, nil
	}
}

// rewriteSchema applies the 3.1 to 3.0 keyword rewrites to one map.
func rewriteSchema(m map[string]any, path string) (map[string]any, error) {
	if types, ok := m["type"].([]any); ok {
		var other []any
		hasNull := false
		for _, t := range types {
			if t == "null" {
				hasNull = true
			} else {
				other = append(other, t)
			}
		}
		if len(other) != 1 {
			return nil, fmt.Errorf("%s: type %v cannot be expressed in OpenAPI 3.0", path, types)
		}
		m["type"] = other[0]
		if hasNull {
			m["nullable"] = true
		}
	}
	for _, key := range []string{"oneOf", "anyOf"} {
		members, ok := m[key].([]any)
		if !ok {
			continue
		}
		var other []any
		for _, s := range members {
			if isNullSchema(s) {
				continue
			}
			other = append(other, s)
		}
		if len(other) == len(members) {
			continue
		}
		m["nullable"] = true
		if len(other) == 1 {
			delete(m, key)
			m["allOf"] = other
		} else {
			m[key] = other
		}
	}
	if v, ok := m["const"]; ok {
		delete(m, "const")
		m["enum"] = []any{v}
	}
	return m, nil
}

func isNullSchema(s any) bool {
	m, ok := s.(map[string]any)
	return ok && len(m) == 1 && m["type"] == "null"
}
